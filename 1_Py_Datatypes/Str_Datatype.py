# str i.e strings are represented using single,double and triple quotes
# single quotes '' 
# double quotes ""
# triple quotes ''' '''   and """ """

# in python we don't have char data type in python 
# even single char is considered as a str

# 1) any number of characters represented inside 1,2,3 quotes are 
# treated as str in python

# application of triple quotes ''' '''   and """ """
# use cases of triple quotes

# first use case 
# to define multiline str literal use triple quotes
a = """ Hello 
        How 
        are 
        you? """
print(a)
#output Hello 
#         How 
#         are 
#         you? 

# second use case 
# write a sentence where I one word will consist single quote
# write a sentence where I one word will consist double quote  
# write a sentence where I one word will consist single quote 
# and another one double quotes
# in this case use triple quotes

b = '''Don't open the file named config"old" right now.'''
print(b) # output Don't open the file named config"old" right now.

